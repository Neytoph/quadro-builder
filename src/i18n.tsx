const dicts: Record<Lang, Dict> = { zh, en, de }

function detect(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY) || localStorage.getItem(ENGINE_KEY)
  if (isLang(stored)) return stored
  const nav = (navigator.language || '').toLowerCase()
  if (nav.startsWith('zh')) return 'zh'
  if (nav.startsWith('de')) return 'de'
  return 'en'
}

function persistLang(l: Lang) {
  localStorage.setItem(STORAGE_KEY, l)
  localStorage.setItem(ENGINE_KEY, l)
}

function applyDocument(lang: Lang, os: OsFamily, translate: (key: string) => string) {
  document.documentElement.lang = HTML_LANG[lang]
  document.documentElement.dataset.os = os
  document.title = translate('app.docTitle')
  const meta = document.querySelector('meta[name="description"]')
  if (meta) meta.setAttribute('content', translate('app.metaDesc'))
}

function shortcutVars(os: OsFamily, lang: Lang): Record<string, string> {
  if (os === 'mac') {
    return {
      mod: '⌘',
      shift: '⇧',
      alt: '⌥',
      undo: '⌘Z',
      redo: '⌘⇧Z',
      save: '⌘S',
      selectAll: '⌘A',
      copy: '⌘C',
      paste: '⌘V',
      copyPaste: '⌘C/V',
      addSelect: 'Shift/⌘',
    }
  }
  const ctrl = lang === 'de' ? 'Strg' : 'Ctrl'
  return {
    mod: ctrl,
    shift: 'Shift',
    alt: 'Alt',
    undo: `${ctrl}+Z`,
    redo: `${ctrl}+Y`,
    save: `${ctrl}+S`,
    selectAll: `${ctrl}+A`,
    copy: `${ctrl}+C`,
    paste: `${ctrl}+V`,
    copyPaste: `${ctrl}+C/V`,
    addSelect: `Shift/${ctrl}`,
  }
}

function lookup(lang: Lang, os: OsFamily, key: string): string {
  const d = dicts[lang]
  const enD = dicts.en
  const tagged = `${key}.${os}`
  return d[tagged] ?? enD[tagged] ?? d[key] ?? enD[key] ?? key
}

function fill(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] != null ? String(vars[k]) : `{${k}}`))
}

const Ctx = createContext<{
  lang: Lang
  os: OsFamily
  setLang: (l: Lang) => void
  t: (key: string, vars?: Record<string, string | number>) => string
} | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [os] = useState<OsFamily>(() => detectOsFamily())
  const [lang, setLangState] = useState<Lang>(() => {
    const l = detect()
    syncEngineLang(l)
    persistLang(l)
    return l
  })
  const setLang = useCallback((l: Lang) => {
    syncEngineLang(l)
    persistLang(l)
    setLangState(l)
  }, [])
  const keys = useMemo(() => shortcutVars(os, lang), [os, lang])
  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    return fill(lookup(lang, os, key), { ...keys, ...vars })
  }, [lang, os, keys])
  useEffect(() => { applyDocument(lang, os, t) }, [lang, os, t])
  const value = useMemo(() => ({ lang, os, setLang, t }), [lang, os, setLang, t])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n() {
  const ctx = useContext(Ctx)
  if (!ctx) throw new Error('useI18n')
  return ctx
}
