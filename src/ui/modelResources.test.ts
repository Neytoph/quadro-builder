// @vitest-environment happy-dom
import {describe,it,expect} from 'vitest'
import {compareRows,missingRows,resourceCsv,mountResources,exportRows} from '../../public/model-resources.js'
const rows=[{group:'tubes',id:'T35',need:6,label:'管 35 cm',image:'/builder/parts/T35.png'},{group:'fittings',id:'textile',need:2,label:'布面',soft:true},{group:'screws',id:'screw_panel',need:8,label:'螺丝'}]
describe('造型资料与库存',()=>{
  it('账号门槛或取消没有产出QDF时，不显示下载成功',async()=>{
    const root=document.createElement('div');document.body.append(root)
    const widget=mountResources(root,{rows:compareRows(rows,null),name:'造型',lang:'zh',stockState:'empty',canNative:true,onExport:async()=>({cancelled:true})})
    root.querySelector<HTMLButtonElement>('[data-mr-action=qdf]')!.click()
    await new Promise(resolve=>setTimeout(resolve,0))
    expect(root.querySelector('.mr-status')?.textContent).toBe('已取消，可重新导出。')
    expect(root.textContent).not.toContain('文件已准备并交给浏览器下载。')
    widget.destroy();root.remove()
  })
  it('完整清单保留颜色和尺寸分行，库存仅记在第一行；缺件继续按规格合并',()=>{
    const source=[{group:'tubes',id:'T35',need:6,owned:2,short:4,label:'管 35 cm',variants:[{need:4,label:'红'},{need:2,label:'蓝'}]}]
    expect(exportRows(source).map((row:{need:number;owned:number|null})=>[row.need,row.owned])).toEqual([[4,2],[2,null]])
    expect(exportRows(source,true)).toHaveLength(1)
    expect(resourceCsv(source,'造型','zh')).toContain('管 35 cm · 红')
  })
  it('未登记与明确零库存分开；按组和规格比较，不使用其他规格抵扣',()=>{
    expect(compareRows(rows,null)[0].short).toBeNull()
    const compared=compareRows(rows,{tubes:{T35:2,T75:99},fittings:{textile:1},screws:{}})
    expect(compared.map((row:{short:number})=>row.short)).toEqual([4,1,8])
    expect(missingRows(compared).map((row:{id:string})=>row.id)).toEqual(['T35','textile'])
    expect(compareRows(rows,{})[0].short).toBe(6)
    expect(()=>compareRows(rows,{tubes:{T35:'invalid'}})).toThrow('Invalid part quantity')
    expect(()=>compareRows(rows,'invalid')).toThrow('Invalid inventory data')
  })
  it('CSV保留真实差额、参考配件和中文；转义引号、换行及表格公式',()=>{
    const csv=resourceCsv(compareRows(rows,{tubes:{T35:2},fittings:{textile:1}}),'=1+1\n"设计"','zh',true)
    expect(csv.startsWith('\uFEFF')).toBe(true)
    expect(csv).toContain('"\'=1+1\n""设计"""')
    expect(csv).toContain('"6","2","4"')
    expect(csv).toContain('参考配件')
    expect(csv).not.toContain('screw_panel')
  })
  it('未知库存停用缺件导出，库存读回后更新清单，查看权限不允许导出说明书',()=>{
    const root=document.createElement('div');document.body.append(root)
    const button=(selector:string)=>root.querySelector<HTMLButtonElement>(selector)!
    const widget=mountResources(root,{rows:compareRows(rows,null),name:'造型',lang:'zh',stockState:'error',canNative:false})
    expect(button('[data-mr-filter=missing]').disabled).toBe(true)
    expect(root.textContent).toContain('暂时无法对比缺件')
    widget.update({rows:compareRows(rows,{tubes:{T35:9},fittings:{textile:2}}),stockState:'ready'})
    expect(root.textContent).toContain('配件齐全')
    expect(button('[data-mr-action=manual]').disabled).toBe(true)
    widget.destroy();root.remove()
  })
  it('配件清单、分层说明书和官方QDF集中，清单筛选与导出共用范围',async()=>{
    const root=document.createElement('div');document.body.append(root);const exports:string[]=[]
    const widget=mountResources(root,{rows:compareRows(rows,{tubes:{T35:2},fittings:{textile:2}}),name:'造型',lang:'zh',stockState:'ready',canNative:true,onExport:async(action:string)=>exports.push(action)})
    expect(root.querySelector('[data-mr-action=downloads]')).toBeNull()
    expect(root.querySelector('[data-mr-downloads]')?.hasAttribute('hidden')).toBe(false)
    expect([...root.querySelectorAll('h2')].map(el=>el.textContent)).toEqual(['配件清单','分层说明书','官方 QDF'])
    expect(root.querySelector('[data-mr-action=retry],[data-mr-action=picture],[data-mr-action=json]')).toBeNull()
    expect(root.querySelector('a')).toBeNull()
    expect(root.querySelector('[data-mr-list]')?.hasAttribute('hidden')).toBe(true)
    root.querySelector<HTMLButtonElement>('[data-mr-expand]')!.click()
    expect(root.querySelector('[data-mr-list]')?.hasAttribute('hidden')).toBe(false)
    const image=root.querySelector('[data-part-id=T35] img')
    expect(image?.getAttribute('src')).toBe('/builder/parts/T35.png')
    widget.update({manualProgress:{page:4,total:6,phase:'render'}})
    expect(root.querySelector('[data-mr-progress]')?.hasAttribute('hidden')).toBe(false)
    expect(root.querySelector('[data-mr-progress-label]')?.textContent).toContain('5 / 6 页')
    expect(root.querySelector('[data-part-id=T35] img')).toBe(image)
    widget.update({manualProgress:null})
    for(const selector of ['[data-mr-action=csv]','[data-mr-filter=missing]'])expect(root.querySelector(selector)?.closest('[data-button-motion="off"]')).toBeTruthy()
    root.querySelector<HTMLButtonElement>('[data-mr-filter=missing]')!.click()
    expect(root.querySelector('[data-mr-list-label]')?.textContent).toBe('只看缺件')
    expect(root.querySelectorAll('[data-part-id]')).toHaveLength(1)
    root.querySelector<HTMLButtonElement>('[data-mr-action=manual]')!.click()
    await new Promise(resolve=>setTimeout(resolve,0))
    expect(exports).toEqual(['manual'])
    root.querySelector<HTMLButtonElement>('[data-mr-action=qdf]')!.click()
    await new Promise(resolve=>setTimeout(resolve,0))
    expect(exports).toEqual(['manual','qdf'])
    expect(root.textContent).toContain('分层说明书')
    expect(root.textContent).not.toContain('预览')
    widget.destroy();root.remove()
  })
})
